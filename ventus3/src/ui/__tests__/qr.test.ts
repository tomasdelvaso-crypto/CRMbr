function comoLinhas(modules: boolean[][]): string[] {
  return modules.map((linha) => linha.map((v) => (v ? '1' : '0')).join(''))
}

describe('encodeQr', () => {
  for (const caso of CASOS) {
    it(`codifica «${caso.texto.slice(0, 32)}» igual que a referência`, () => {
      const qr = encodeQr(caso.texto)
      expect(qr.version).toBe(caso.version)
      expect(qr.size).toBe(caso.size)
      expect(comoLinhas(qr.modules)).toEqual(caso.linhas)
    })
  }

  it('recusa um texto que não cabe na versão 10 em vez de emitir lixo', () => {
    expect(() => encodeQr('x'.repeat(300))).toThrow(/longo demais/)
  })

  it('os três buscadores e os separadores estão no lugar', () => {
    const { modules, size } = encodeQr('https://ventus.ventapel.com.br/instalar')
    for (const [linha, coluna] of [
      [0, 0],
      [0, size - 7],
      [size - 7, 0],
    ] as const) {
      // Anel externo escuro, anel interno claro, núcleo escuro.
      expect(modules[linha]?.[coluna]).toBe(true)
      expect(modules[linha + 1]?.[coluna + 1]).toBe(false)
      expect(modules[linha + 3]?.[coluna + 3]).toBe(true)
    }
    // Separador: la columna 7 junto al buscador de arriba a la izquierda es
    // clara de punta a punta.
    for (let r = 0; r <= 7; r += 1) expect(modules[r]?.[7]).toBe(false)
  })

  it('o módulo escuro fixo existe — é o único módulo que nunca muda', () => {
    const { modules, size } = encodeQr('Ventus')
    expect(modules[size - 8]?.[8]).toBe(true)
  })
})
