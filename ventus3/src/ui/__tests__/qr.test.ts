// El codificador de QR está escrito a mano (ver el encabezado de src/ui/qr.ts),
// así que necesita una prueba que no sea «no lanza»: un QR mal codificado
// dibuja igual de lindo y no escanea, y eso sólo se descubre con el teléfono
// del vendedor en la mano el día de la instalación.
//
// Las matrices esperadas se generaron con `python-qrcode` (implementación de
// referencia independiente, ISO/IEC 18004) en nivel de corrección M, modo
// byte, sin zona tranquila, con la máscara de MENOR penalización según las
// cuatro reglas de la norma. Se comparan módulo por módulo, incluidos el
// patrón de máscara y la información de formato: si la selección de máscara se
// rompiera, el formato dejaría de corresponder al patrón aplicado y el lector
// no podría desenmascarar nada.
//
// Esta prueba ya encontró tres defectos reales:
//   · el separador de los buscadores pintado como borde (marco negro de más),
//   · la información de formato transpuesta (fila 8 ↔ columna 8),
//   · el zigzag de datos espejado al saltar la columna 6 del temporizador.

